-- 0119 — Zwei Sortierschemata für eine Charge halten die Rechnung nicht an
--
-- WARUM
--
-- Der Betrieb hat zum ersten Mal Sortierdateien mit Datum eingelesen. Danach
-- brach „Neu rechnen" ab: „could not create unique index erg_kaliber_eindeutig".
--
-- Mit dem Datum findet jede Datei ihre Arbeit, und mit der Arbeit ihr
-- Sortierschema — je Käufer und Datum eigene Bänder (sortierschema_fuer). Hat
-- eine Charge Läufe mit zwei Schemata, steht Kaliber 1 einmal als 600–1100 g
-- und einmal als 600–1200 g da: mv_kaliber_verteilung zählt sie zu Recht
-- getrennt (sie gruppiert nach den Bandgrenzen). Der Schlüssel, mit dem
-- erg_kaliber nachts nebenläufig erneuert wird, kannte die Bandgrenzen aber
-- nicht (Charge, Klasse, Kaliber). Der Index stand aus einer früheren Nacht
-- schon da; beim normalen Erneuern baut Postgres ihn neu, findet zwei Zeilen
-- für denselben Schlüssel — und die ganze Rechnung bricht ab. Nachgestellt in
-- der Beispieldatenbank: genau dieser Fehler.
--
-- Jetzt:
--   1. Der Schlüssel von erg_kaliber trägt die Bandgrenzen; der alte Index geht
--      weg und entsteht in der nächsten Nacht neu.
--      Dasselbe bei erg_ausschuss: Es hat eine Zeile je Sortierlauf, und eine
--      Arbeit kann zwei Dateien haben, eine Charge mehrere Läufe ohne Arbeit —
--      (Weg, Charge, Arbeit) ist dort kein Schlüssel, und einen anderen gibt
--      die Ansicht nicht her. Sie wird ohne Index erneuert (sie ist klein).
--   2. Der Index von mv_kaliber_verteilung trägt auch die obere Bandgrenze
--      (zwei Schemata mit gleicher unterer, anderer oberer Grenze).
--   3. Allgemein: Gibt beim Erneuern ein eindeutiger Index die Daten nicht mehr
--      her, wird er entfernt, die Ansicht normal erneuert, und die Rechnung läuft
--      weiter. Was entfernt wurde, steht in auswertung_index_entfernt — damit ein
--      falscher Schlüssel auffällt, statt die Zahlen anzuhalten.

-- =====================================================================
-- 1. Wo ein Index entfernt wurde
-- =====================================================================
create table if not exists auswertung_index_entfernt (
  id     bigint generated by default as identity primary key,
  sicht  text not null,
  grund  text not null,
  ts     timestamptz not null default now()
);
comment on table auswertung_index_entfernt is
  'Wenn beim Erneuern ein eindeutiger Index die Daten nicht mehr hergab (0119): welche Ansicht, warum, wann. Die Rechnung lief weiter; der Index wurde entfernt (bei erg_* entsteht er in der nächsten Nacht aus auswertung_schluessel neu — und fällt wieder hier auf, wenn der Schlüssel falsch ist).';
alter table auswertung_index_entfernt enable row level security;
drop policy if exists auswertung_index_entfernt_lesen on auswertung_index_entfernt;
create policy auswertung_index_entfernt_lesen on auswertung_index_entfernt for select to authenticated using (ist_admin());
grant select on auswertung_index_entfernt to authenticated;

