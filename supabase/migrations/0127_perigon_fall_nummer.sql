-- 0127 — Jeder Perigon-Fall hat eine Nummer, die bleibt
--
-- WARUM
--
-- Der Betrieb, 24. Oktober, zum Reiter Perigon: „mach es angenehmer … damit
-- ich Fall für Fall angenehm abarbeiten kann … dann kann ich das mit meinem
-- Chef besprechen … und dann wirst du von mir eine Nachricht kriegen, wo ich
-- dir sage, wie wir mit den einzelnen Fällen umgehen werden."
--
-- Wer über Fälle spricht — im Büro, mit dem Chef, in einer Sprachnachricht —,
-- braucht für jeden ein Wort, das ihn eindeutig nennt. „Die Position
-- eins-drei-vier-sieben-sieben-neun" sagt niemand; „Fall 4" schon. Seit
-- Runde BF fasst die App zusammen, was eine Frage ist (alles zu einer Charge,
-- alle Perigon-Zeilen einer Art, eine Sache im Chargenregister) — welcher
-- Fall was umfasst, bestimmt die App (src/auswertung/faelle.ts). Hier steht
-- nur, welche Nummer jeder Fall trägt:
--
-- perigon_fall_nr — je Fall (seine Kennung, z. B. „charge:1626", „art:mix",
--   „stammdaten:1649:perigon_doppelt") eine Nummer. Vergeben, wenn die App
--   den Fall zum ersten Mal zeigt, in der Folge ihrer Liste (das Wichtigste
--   zuerst); nie wieder vergeben, nie geändert, nie gelöscht. Verschwindet
--   ein Fall und kommt wieder, trägt er dieselbe Nummer.
--
-- perigon_fall_nummern(kennungen) — gibt jedem Fall seine Nummer; was noch
--   keine hat, bekommt die nächste. Nummern vergibt nur der Betriebsleiter
--   (der Reiter ist seiner); lesen dürfen alle Angemeldeten.

create table if not exists perigon_fall_nr (
  fall text primary key check (char_length(fall) between 3 and 300),
  nr   int  not null generated by default as identity,
  ts   timestamptz not null default now()
);
create unique index if not exists perigon_fall_nr_nr on perigon_fall_nr (nr);
comment on table perigon_fall_nr is
  'Je Perigon-Fall (Kennung der App: charge:<nr>, art:<art>, Schlüssel einer Sache im Chargenregister) eine Nummer, die bleibt (0127). Vergeben von perigon_fall_nummern() in der Folge der Liste; nie neu vergeben, nie geändert, nie gelöscht.';
alter table perigon_fall_nr enable row level security;
drop policy if exists perigon_fall_nr_lesen on perigon_fall_nr;
create policy perigon_fall_nr_lesen on perigon_fall_nr for select to authenticated using (true);
revoke all on perigon_fall_nr from anon, public;
grant select on perigon_fall_nr to authenticated;

create or replace function perigon_fall_nummern(p_faelle text[]) returns table (fall text, nr int)
language plpgsql security definer set search_path = public as $$
begin
  if p_faelle is null or cardinality(p_faelle) = 0 then return; end if;
  -- Neue Nummern nur vom Betriebsleiter; wer sonst fragt, bekommt die bekannten.
  if auth.uid() is null or ist_admin() then
    insert into perigon_fall_nr (fall)
    select x.f from (
      select u.f, min(u.i) as i from unnest(p_faelle) with ordinality as u(f, i)
       where u.f is not null and char_length(u.f) between 3 and 300
       group by u.f
    ) x
     where not exists (select 1 from perigon_fall_nr n where n.fall = x.f)
     order by x.i
    on conflict on constraint perigon_fall_nr_pkey do nothing;
  end if;
  return query select n.fall, n.nr from perigon_fall_nr n where n.fall = any (p_faelle) order by n.nr;
end $$;
comment on function perigon_fall_nummern(text[]) is
  'Gibt jedem genannten Perigon-Fall seine Nummer (0127); was noch keine hat, bekommt die nächste — in der Folge, in der die Fälle genannt sind. Neue Nummern nur für den Betriebsleiter; die Nummer eines Falls ändert sich nie.';
revoke all on function perigon_fall_nummern(text[]) from public;
grant execute on function perigon_fall_nummern(text[]) to authenticated;

